-- SECCIÓN 1.1 — Crear la base de datos
CREATE DATABASE IF NOT EXISTS BIBLIOTECA_UNI;
USE BIBLIOTECA_UNI;

-- SECCIÓN 1.2 — Crear las tablas
-- Orden de ejecución: primero las tablas que NO tienen claves foráneas,
-- después las que apuntan a ellas (una FK solo puede referenciar una tabla
-- que ya existe).
--   CIUDAD -> CAMPUS -> CARRERAS -> ESTUDIANTES
--                    -> FUNCIONARIOS
--   AUTORES, EDITORIALES, BIBLIOTECA, TIPO -> LIBROS
--   ESTUDIANTES, FUNCIONARIOS, LIBROS -> PRESTAMO

CREATE TABLE CIUDAD (
    ID_CIUDAD INT PRIMARY KEY,
    NOMBRE    VARCHAR(60) NOT NULL
);

CREATE TABLE CAMPUS (
    ID_CAMPUS INT PRIMARY KEY,
    NOMBRE    VARCHAR(80) NOT NULL,
    ID_CIUDAD INT NOT NULL,
    FOREIGN KEY (ID_CIUDAD) REFERENCES CIUDAD(ID_CIUDAD)
);

CREATE TABLE CARRERAS (
    ID_CARRERA INT PRIMARY KEY,
    NOMBRE     VARCHAR(80) NOT NULL,
    ID_CAMPUS  INT NOT NULL,
    FOREIGN KEY (ID_CAMPUS) REFERENCES CAMPUS(ID_CAMPUS)
);

CREATE TABLE ESTUDIANTES (
    RUT_EST    VARCHAR(12) PRIMARY KEY,
    NOMBRES    VARCHAR(60) NOT NULL,
    APELLIDOS  VARCHAR(60) NOT NULL,
    EDAD       INT,
    FONO       VARCHAR(20),
    DIRECCION  VARCHAR(120),
    ID_CARRERA INT NOT NULL,
    FOREIGN KEY (ID_CARRERA) REFERENCES CARRERAS(ID_CARRERA)
);

CREATE TABLE FUNCIONARIOS (
    RUT_FUNC  VARCHAR(12) PRIMARY KEY,
    NOMBRES   VARCHAR(60) NOT NULL,
    APELLIDOS VARCHAR(60) NOT NULL,
    EDAD      INT,
    DIRECCION VARCHAR(120),
    SALUD     VARCHAR(30),
    ID_CAMPUS INT NOT NULL,
    FOREIGN KEY (ID_CAMPUS) REFERENCES CAMPUS(ID_CAMPUS)
);

CREATE TABLE AUTORES (
    RUT_AUTOR VARCHAR(12) PRIMARY KEY,
    NOMBRES   VARCHAR(60) NOT NULL,
    APELLIDOS VARCHAR(60) NOT NULL
);

CREATE TABLE EDITORIALES (
    ID_EDIT INT PRIMARY KEY,
    NOMBRE  VARCHAR(80) NOT NULL,
    PAIS    VARCHAR(50)
);

CREATE TABLE BIBLIOTECA (
    ID_BIBLIO  INT PRIMARY KEY,
    BIBLIOTECA VARCHAR(80) NOT NULL
);

CREATE TABLE TIPO (
    ID_TIPO INT PRIMARY KEY,
    TIPO_P  VARCHAR(50) NOT NULL
);

CREATE TABLE LIBROS (
    COD_LIBRO INT PRIMARY KEY,
    TITULO    VARCHAR(150) NOT NULL,
    AGNO      INT,
    ID_BIBLIO INT NOT NULL,
    ID_TIPO   INT NOT NULL,
    RUT_AUTOR VARCHAR(12) NOT NULL,
    ID_EDIT   INT NOT NULL,
    FOREIGN KEY (ID_BIBLIO) REFERENCES BIBLIOTECA(ID_BIBLIO),
    FOREIGN KEY (ID_TIPO)   REFERENCES TIPO(ID_TIPO),
    FOREIGN KEY (RUT_AUTOR) REFERENCES AUTORES(RUT_AUTOR),
    FOREIGN KEY (ID_EDIT)   REFERENCES EDITORIALES(ID_EDIT)
);

-- Clave primaria compuesta por las tres FK: un préstamo queda identificado
-- por QUÉ estudiante, QUÉ funcionario y QUÉ libro (ver doc/questions.md).
CREATE TABLE PRESTAMO (
    RUT_EST   VARCHAR(12) NOT NULL,
    RUT_FUNC  VARCHAR(12) NOT NULL,
    COD_LIBRO INT NOT NULL,
    FECHA_P   DATE NOT NULL,
    FECHA_E   DATE,
    PRIMARY KEY (RUT_EST, RUT_FUNC, COD_LIBRO),
    FOREIGN KEY (RUT_EST)   REFERENCES ESTUDIANTES(RUT_EST),
    FOREIGN KEY (RUT_FUNC)  REFERENCES FUNCIONARIOS(RUT_FUNC),
    FOREIGN KEY (COD_LIBRO) REFERENCES LIBROS(COD_LIBRO)
);
